import { readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

// Runs the exact common module in Chromium; no simulated DOM and no external API.
export async function checkPicker(page, expect) {
  const source = await readFile(fileURLToPath(new URL('../public/transport-grid/grid.js', import.meta.url)), 'utf8')
  const css = await readFile(fileURLToPath(new URL('../public/transport-grid/grid.css', import.meta.url)), 'utf8')
  await page.evaluate(css => { const style=document.createElement('style'); style.id='picker-regression-css'; style.textContent=css; document.head.append(style) }, css)
  await page.evaluate(async source => {
    const { mountTransportGrid } = await import('data:text/javascript;base64,' + btoa(unescape(encodeURIComponent(source))))
    const root = document.createElement('div'); root.id = 'picker-regression'; (document.querySelector('main') ?? document.body).append(root)
    const row = { user_id: 1, name: '候補確認児童', school_name: '候補第一小学校', exists: true, snapshot: 'test', pickup_time: '14:30', pickup_location: 'home', pickup_staff_id: 7, dropoff_time: '17:30', dropoff_location: 'home', dropoff_staff_id: null }
    const config = { rows: [row, { ...row, user_id: 2, name: '候補確認児童2', school_name: '候補第二小学校' }], times: ['14:30', '15:00', '17:30'], locations: { school: '学校', home: '自宅' }, staff: [{ id: 7, name: '候補職員A' }, { id: 8, name: '候補職員B' }] }
    window.pickerSaves = []; window.disposePicker = mountTransportGrid(root, { date: '2026-12-01', load: async () => config, save: async payload => { window.pickerSaves.push(payload); for (const changed of payload.rows) Object.assign(config.rows.find(person => person.user_id === changed.user_id), changed) } })
  }, source.slice(0, source.indexOf("if (typeof document !== 'undefined')")))
  const root = page.locator('#picker-regression')
  const direction = root.getByLabel('表示する送迎', {exact:true})
  if(page.viewportSize().width < 768) {
    await expect(direction).toBeVisible()
    await expect(direction).toHaveValue('pickup')
    await direction.selectOption('dropoff')
    await expect(root.getByRole('combobox',{name:'候補確認児童 送り時刻',exact:true})).toBeVisible()
    await expect(root.getByRole('combobox',{name:'候補確認児童 迎え時刻',exact:true})).toHaveCount(0)
    await direction.selectOption('pickup')
  } else await expect(direction).not.toBeVisible()
  const tools = root.getByRole('button', { name: '予約の追加・削除／一括変更', exact: true })
  const bulk = root.getByLabel('一括変更の入力値', { exact: true })
  await expect(tools).toHaveAttribute('aria-expanded', 'false')
  await expect(bulk).not.toBeVisible()
  await tools.focus(); await tools.press('Enter')
  await expect(bulk).toBeVisible()
  await bulk.fill('15:00')
  await tools.click()
  await expect(bulk).not.toBeVisible()
  await tools.press('Enter')
  await expect(bulk).toHaveValue('15:00')
  // Read both rows in the same frame while the accordion may still be animating.
  const positions = await root.evaluate(root => ({
    addBottom: root.querySelector('.tg-add-row').getBoundingClientRect().bottom,
    actionsTop: root.querySelector('.tg-reservation-actions').getBoundingClientRect().top,
  }))
  expect(positions.actionsTop).toBeGreaterThanOrEqual(positions.addBottom)
  await expect(root.getByRole('group', { name: '選択した児童の一括変更', exact: true }).getByRole('button', { name: '選択した児童に適用', exact: true })).toBeVisible()
  await root.getByRole('checkbox', { name: '表示中の児童をすべて選択', exact: true }).check()
  await root.getByLabel('一括変更する列', { exact: true }).selectOption('1')
  await bulk.fill('学校')
  await root.getByRole('button', { name: '選択した児童に適用', exact: true }).click()
  await expect(root.getByRole('combobox', { name: '候補確認児童 迎え場所', exact: true })).toHaveValue('候補第一小学校')
  await expect(root.getByRole('combobox', { name: '候補確認児童2 迎え場所', exact: true })).toHaveValue('候補第二小学校')
  await root.getByRole('button', { name: '変更をまとめて保存', exact: true }).click()
  await expect(root.getByText('変更をまとめて保存しました。', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => window.pickerSaves.at(-1).rows.map(row => ({ user_id: row.user_id, location: row.pickup_location })))).toEqual([{ user_id: 1, location: 'school' }, { user_id: 2, location: 'school' }])
  await expect(root.getByRole('combobox', { name: '候補確認児童 迎え場所', exact: true })).toHaveValue('候補第一小学校')
  await expect(root.getByRole('combobox', { name: '候補確認児童2 迎え場所', exact: true })).toHaveValue('候補第二小学校')
  await tools.click()
  const input = root.getByRole('combobox', { name: '候補確認児童 迎え担当', exact: true })
  const toggle = root.getByRole('button', { name: '候補確認児童 迎え担当の候補をすべて表示', exact: true })
  await expect(input).toHaveValue('候補職員A')
  await toggle.click()
  await expect(page.getByRole('option', { name: '候補職員A', exact: true })).toBeVisible()
  await expect(page.getByRole('option', { name: '候補職員B', exact: true })).toBeVisible()
  await expect(input).toHaveValue('候補職員A') // Opening must not dirty or clear the value.
  await expect(root.getByRole('button', { name: '変更をまとめて保存', exact: true })).toBeDisabled()
  const optionsId = await input.getAttribute('aria-controls')
  const options = page.locator('#' + optionsId)
  const box = await options.boundingBox()
  expect(box.x).toBeGreaterThanOrEqual(0); expect(box.x + box.width).toBeLessThanOrEqual(page.viewportSize().width)
  await page.getByRole('option', { name: '候補職員A', exact: true }).click()
  await expect(root.getByRole('button', { name: '変更をまとめて保存', exact: true })).toBeDisabled()
  await toggle.click()
  const staffB = page.getByRole('option', { name: '候補職員B', exact: true })
  if (page.viewportSize().width < 600) await staffB.tap(); else await staffB.click()
  await expect(input).toHaveAttribute('aria-expanded', 'false')
  await expect(input).toHaveValue('候補職員B')
  await input.fill('候補職員A')
  await expect(page.getByRole('option', { name: '候補職員B', exact: true })).toHaveCount(0)
  await input.press('Escape'); await toggle.click()
  await expect(page.getByRole('option', { name: '候補職員B', exact: true })).toBeVisible()
  await input.press('Escape'); await input.press('ArrowDown'); await input.press('ArrowDown'); await input.press('Enter')
  await expect(input).toHaveValue('候補職員B')
  await input.press('ArrowUp'); await input.press('Enter')
  await expect(input).toHaveValue('候補職員B')
  await root.getByRole('button', { name: '変更をまとめて保存', exact: true }).click()
  await expect(root.getByText('変更をまとめて保存しました。', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => window.pickerSaves.at(-1).rows[0].pickup_staff_id)).toBe(8)
  expect((await root.locator('thead th').allTextContents()).map(text=>text.trim())).toEqual(['選択','児童','迎え時刻','迎え場所','迎え担当','迎え担当2','送り時刻','送り場所','送り担当','送り担当2'])
  if(page.viewportSize().width < 768) await direction.selectOption('all')
  // Paste both assignees for both directions, then inspect the saved canonical IDs.
  await input.evaluate(input => {
    const clipboardData=new DataTransfer();clipboardData.setData('text/plain','候補職員B\t候補職員A\t17:30\t自宅\t候補職員A\t候補職員B')
    input.dispatchEvent(new ClipboardEvent('paste',{clipboardData,bubbles:true,cancelable:true}))
  })
  const commit=root.getByRole('button',{name:'変更をまとめて保存',exact:true})
  await commit.click()
  await expect(root.getByText('変更をまとめて保存しました。',{exact:true})).toBeVisible()
  expect(await page.evaluate(()=>window.pickerSaves.at(-1).rows[0])).toMatchObject({pickup_staff_id:8,pickup_assistant_staff_id:7,dropoff_staff_id:7,dropoff_assistant_staff_id:8})
  await expect(root.getByRole('combobox',{name:'候補確認児童 迎え担当2',exact:true})).toHaveValue('候補職員A')
  await expect(root.getByRole('combobox',{name:'候補確認児童 送り担当2',exact:true})).toHaveValue('候補職員B')
  // An ID and a typed label for the same person are the same assignee.
  const assistant=root.getByRole('combobox',{name:'候補確認児童 迎え担当2',exact:true})
  await assistant.evaluate(input=>{
    const clipboardData=new DataTransfer();clipboardData.setData('text/plain','候補職員B')
    input.dispatchEvent(new ClipboardEvent('paste',{clipboardData,bubbles:true,cancelable:true}))
  })
  const savedCount=await page.evaluate(()=>window.pickerSaves.length)
  await commit.click()
  await expect(assistant).toHaveAttribute('aria-invalid','true')
  expect(await page.evaluate(()=>window.pickerSaves.length)).toBe(savedCount)
  // Whitespace pasted into an optional assignee is a valid clearing operation.
  await input.evaluate(input=>{
    const clipboardData=new DataTransfer();clipboardData.setData('text/plain','　\t　')
    input.dispatchEvent(new ClipboardEvent('paste',{clipboardData,bubbles:true,cancelable:true}))
  })
  await commit.click()
  await expect(root.getByText('変更をまとめて保存しました。',{exact:true})).toBeVisible()
  expect(await page.evaluate(()=>window.pickerSaves.at(-1).rows[0])).toMatchObject({pickup_staff_id:null,pickup_assistant_staff_id:null})
  const last=root.getByRole('combobox',{name:'候補確認児童 送り担当2',exact:true})
  await last.click();await last.press('Shift+ArrowLeft');await last.press('Shift+ArrowRight')
  await expect(last).toBeFocused()
  await page.evaluate(() => { window.disposePicker(); document.getElementById('picker-regression-css')?.remove() })
  await expect(options).toHaveCount(0)
}


